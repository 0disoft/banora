/** Explicit, DOM-free widget messages; overrides are literal and view-owned. */
export function createPuzzleMessages(options: PuzzleLocaleOptions = {}): PuzzleMessages {
  const ui = createUiMessages({ locale: options.locale });
  const messages: PuzzleMessages = {
    ...catalogs[options.locale ?? 'en'],
    black: ui.black,
    white: ui.white,
    pass: ui.pass,
    rejected: ui.rejected,
  };
  return resolveWidgetMessages(messages, options.messages);
}
