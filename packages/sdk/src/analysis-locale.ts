/** Explicit and DOM-free; overrides share the widget literal-text policy. */
export function createAnalysisMessages(options: AnalysisLocaleOptions = {}): AnalysisMessages {
  const ui = createUiMessages({ locale: options.locale }),
    locale = options.locale ?? 'en';
  return resolveWidgetMessages(
    {
      ...catalogs[locale],
      ...analysisFailureCatalogs[locale],
      black: ui.black,
      white: ui.white,
      pass: ui.pass,
    },
    options.messages,
  );
}
const failureKeys = {
  'invalid-context': 'errorContext',
  'unsupported-history': 'errorHistory',
  'invalid-request': 'errorRequest',
  'invalid-result': 'errorResult',
  provider: 'errorProvider',
  unsupported: 'errorUnsupported',
  cancelled: 'errorCancelled',
  stale: 'errorStale',
  disposed: 'errorDisposed',
  busy: 'errorBusy',
  limit: 'errorLimit',
} as const satisfies Record<AnalysisFailureReason, keyof AnalysisMessages>;

/** Public provider-authored diagnostics are data, not templates to translate. */
export function analysisFailureMessage(
  failure: AnalysisFailure,
  messages: AnalysisMessages,
): string {
  if (failure.messageSource === 'provider') return failure.message;
  return messages[
    Object.hasOwn(failureKeys, failure.reason) ? failureKeys[failure.reason] : 'errorProvider'
  ];
}
