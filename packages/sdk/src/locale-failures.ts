/** Localized owned feedback; unknown codes use a safe explanation rather than raw text. */
export function formatUiFailure(
  code: string,
  options: { readonly locale?: BanoraLocale } = {},
): string {
  const locale = options.locale ?? 'en';
  if (typeof locale !== 'string' || !Object.hasOwn(catalogs, locale))
    throw new TypeError('Unsupported UI locale');
  if (typeof code !== 'string') throw new TypeError('Failure code must be a string');
  return catalogs[locale][Object.hasOwn(en, code) ? (code as keyof typeof en) : 'unknown'];
}
