import { describe, expect, test } from 'bun:test';
import { RecordController } from '../src/controller.js';
import { stoneAt } from '../src/core.js';
import { parseSgf } from '../src/sgf.js';

describe('extended record editing', () => {
  test('subtree removal preserves other games, moves a deleted cursor, and restores IDs with Undo', () => {
    const controller = new RecordController({sgf:'(;SZ[9](;B[aa];W[bb]XX[keep])(;B[cc]))(;SZ[13];B[dd])'});
    const initial = controller.getState();
    const removed = initial.node.children[0]!;
    controller.goTo(removed.children[0]!.id);
    const selected = controller.getState();
    expect(controller.removeBranch(removed.id).ok).toBe(true);
    expect(controller.getState().node.id).toBe(initial.node.id);
    expect(controller.getState().node.children.map(node => node.properties.B?.[0])).toEqual(['cc']);
    expect(controller.getState().record.games[1]).toBe(initial.record.games[1]);
    expect(controller.goTo(removed.id).ok).toBe(false);
    controller.undo();
    expect(controller.getState().node.id).toBe(selected.node.id);
    expect(controller.getState().node.properties.XX).toEqual(['keep']);
    expect(controller.getState().dirty).toBe(false);
    controller.redo();
    expect(controller.getState().dirty).toBe(true);
  });
  test('reordering changes default continuation, keeps the cursor, and rejects root/index errors atomically', () => {
    const controller = new RecordController({sgf:'(;SZ[9](;B[aa])(;B[bb])(;B[cc]))'});
    const root = controller.getState().node;
    const third = root.children[2]!.id;
    controller.goTo(third);
    expect(controller.reorderBranch(third, 0).ok).toBe(true);
    expect(controller.getState().node.id).toBe(third);
    controller.previous(); controller.next();
    expect(controller.getState().node.id).toBe(third);
    const before = controller.getState();
    expect(controller.reorderBranch(third, 3)).toEqual({ok:false, reason:'invalid-edit'});
    expect(controller.removeBranch(root.id)).toEqual({ok:false, reason:'invalid-edit'});
    expect(controller.getState()).toBe(before);
    controller.undo();
    expect(controller.getState().dirty).toBe(false);
    expect(controller.getState().node.id).toBe(third);
  });
  test('removing a different branch preserves the selected node and position', () => {
    const controller = new RecordController({sgf:'(;SZ[9](;B[aa])(;B[bb]))'});
    const root = controller.getState().node;
    controller.next(1);
    const before = controller.getState();
    controller.removeBranch(root.children[0]!.id);
    expect(controller.getState().node.id).toBe(before.node.id);
    expect(controller.getState().position.board).toEqual(before.position.board);
  });
  test('free setup patches compressed points without captures, and never mixes setup into a move', () => {
    const controller = new RecordController({sgf:'(;SZ[5]AB[aa:ba]XX[preserve];W[cc])'});
    expect(controller.setSetup([{x:0,y:0,color:'white'}], 'white').ok).toBe(true);
    expect(stoneAt(controller.getState().position, {x:1,y:0})).toBe('black');
    expect(stoneAt(controller.getState().position, {x:0,y:0})).toBe('white');
    expect(controller.getState().position.moveNumber).toBe(0);
    controller.next();
    const move = controller.getState().node.id;
    controller.setSetup([{x:2,y:2,color:null}], 'black');
    const setup = controller.getState();
    expect(setup.node.properties.W).toBeUndefined();
    expect(setup.node.properties.AE).toEqual(['cc']);
    expect(setup.position.moveNumber).toBe(1);
    expect(setup.position.captures).toEqual({black:0,white:0});
    expect(setup.path.at(-2)).toBe(move);
    const before = setup;
    expect(controller.setSetup([{x:0,y:0,color:'black'}, {x:0,y:0,color:'white'}]).ok).toBe(false);
    expect(controller.getState()).toBe(before);
    const reopened = new RecordController({sgf:controller.prepareExport().text});
    reopened.next(); reopened.next();
    expect(reopened.getState().position.board).toEqual(setup.position.board);
    expect(reopened.getState().record.games[0]!.properties.XX).toEqual(['preserve']);
    controller.undo();
    expect(controller.getState().node.id).toBe(move);
    expect(stoneAt(controller.getState().position, {x:2,y:2})).toBe('white');
  });
  test('lines are undirected, arrows directed, and all markup survives export/reopen and Undo', () => {
    const controller = new RecordController({sgf:'(;SZ[9]LN[aa:bb]AR[cc:dd]XX[keep])'});
    const before = controller.getState();
    controller.setConnection({x:1,y:1},{x:0,y:0}, 'line');
    expect(controller.getState()).toBe(before);
    controller.setConnection({x:3,y:3},{x:2,y:2}, 'arrow');
    expect(controller.getState().connections.length).toBe(3);
    expect(Object.isFrozen(controller.getState().connections[0]!.from)).toBe(true);
    const reopened = new RecordController({sgf:controller.prepareExport().text});
    expect(reopened.getState().connections).toEqual(controller.getState().connections);
    controller.undo(); expect(controller.getState().dirty).toBe(false);
    controller.setConnection({x:1,y:1},{x:0,y:0}, 'line', false);
    expect(controller.getState().node.properties.LN).toBeUndefined();
    controller.undo(); expect(controller.getState().dirty).toBe(false);
    expect(controller.setConnection({x:0,y:0},{x:0,y:0}, 'line').ok).toBe(false);
    for (const input of ['(;AR[aa:aa])','(;LN[aa:bb][bb:aa])','(;AR[aa:bb][aa:bb])','(;LN[aa:zz])']) expect(parseSgf(input).ok).toBe(false);
  });
  test('node limits reject appended setup atomically but allow reuse of an existing move', () => {
    const controller = new RecordController({sgf:'(;SZ[9];B[aa])', limits:{maxNodes:2}});
    expect(controller.play({x:0,y:0}).ok).toBe(true);
    const before = controller.getState();
    expect(controller.setSetup([{x:1,y:1,color:'white'}]).ok).toBe(false);
    expect(controller.getState()).toBe(before);
  });
});
