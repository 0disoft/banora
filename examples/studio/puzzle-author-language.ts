const keys = Object.keys(englishAuthorMessages) as (keyof AuthorMessages)[];
const translated = Object.fromEntries(
  Object.entries({ ...values, ...extraAuthorValues }).map(([locale, rows]) => {
    if (rows.length !== keys.length) throw new Error('Incomplete puzzle authoring translation');
    return [
      locale,
      Object.freeze(Object.fromEntries(keys.map((key, index) => [key, rows[index]]))),
    ];
  }),
);
export const authorMessages = Object.freeze({
  en: englishAuthorMessages,
  ...translated,
}) as Readonly<Record<BanoraLocale, AuthorMessages>>;
